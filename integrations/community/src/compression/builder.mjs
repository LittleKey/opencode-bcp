/**
 * Compression bundle builder.
 *
 * Emits a self-contained, relocatable-by-rebuild bundle:
 *   outDir/
 *     package.json            — host-facing plugin package (v1 + v2 entries)
 *     deps.json               — explicit dependency paths + pinned sha256s
 *     entry-core.mjs          — guarded entry factories
 *     compression/engine-select.mjs — selection/verification logic
 *                               (source-tree relative layout preserved)
 *     lib/hash.mjs            — shared helpers
 *     lib/engine-registry.mjs — per-bundle exactly-one-engine guard
 *     v1.mjs                  — v1 host plugin (default export = server fn;
 *                               this default is the ONLY supported export)
 *     v2.mjs                  — v2 host plugin (Plugin surface: default
 *                               {id, setup} + named id/setup)
 *     legacy-acp/opencode-acp/dist/index.js
 *                             — BYTE-EXACT copy of the repaired ACP entry;
 *                               packaging copies this tree into the explicit
 *                               BILI_OPENCODE_ACP_SPEC slot, and the arm-time
 *                               gate verifies the slot bytes against the pin
 *     manifest.json           — support/hash/tooling/removal documentation
 *
 * Install contract (coherent by construction): the emitted slot file is a
 * direct byte copy of the verified repaired entry, so the documented install
 * steps produce a slot whose sha256 equals the pinned repaired hash. Both the
 * builder (post-copy verification) and the arm-time gate (planLegacySelection)
 * independently enforce this — a slot with foreign bytes is refused, never
 * silently accepted and never silently replaced by stock candidates.
 *
 * Nothing here writes outside outDir, installs anything, or touches host state.
 */

import { cpSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { sha256File } from "../lib/hash.mjs";
import { verifyBillionContextPackage } from "./engine-select.mjs";

const srcRoot = join(dirname(fileURLToPath(import.meta.url)), "..");

export const BILLION_CONTEXT_VERSION = "0.1.175";

function writeFile(outDir, relPath, content) {
  const target = join(outDir, relPath);
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, content, "utf8");
  return target;
}

const V1_ENTRY_TEMPLATE = `// Generated by opencode-community-compat builder — do not edit.
// v1 host plugin. SUPPORTED LOADER SURFACE: the default export only, a
// server(ctx) -> hooks function (directly, or as .server of a dual-shape
// default inside the pinned artifact). No other exports are part of the
// contract: hosts must not introspect this module for factories.
// Guarded lazily on first arm: dependency hash gates + explicit legacy-ACP
// selection + per-bundle engine registry claim all run before the pinned
// billion-context entry is imported.
import { createCompressionV1Entry } from "./entry-core.mjs";

let entryPromise;
async function lazy() {
  if (!entryPromise) {
    entryPromise = createCompressionV1Entry().catch((err) => {
      entryPromise = undefined;
      throw err;
    });
  }
  return entryPromise;
}

export default async function server(ctx) {
  const entry = await lazy();
  return await entry.server(ctx);
}
`;

const V2_ENTRY_TEMPLATE = `// Generated by opencode-community-compat builder — do not edit.
// v2 host plugin. SUPPORTED LOADER SURFACE (Plugin interface): default export
// { id, setup } plus the named id / setup. setup() runs the guarded lazy build
// on first call; the id below is the wrapper's own id — the pinned artifact's
// id is validated at arm time. No factory exports: hosts must not introspect
// this module beyond the Plugin surface.
import { createCompressionV2Entry } from "./entry-core.mjs";

export const id = "community-compression-v2";

let entryPromise;
async function lazy() {
  if (!entryPromise) {
    entryPromise = createCompressionV2Entry().catch((err) => {
      entryPromise = undefined;
      throw err;
    });
  }
  return entryPromise;
}

export async function setup(ctx) {
  const entry = await lazy();
  return await entry.setup(ctx);
}

export default { id, setup };
`;

/**
 * Build the compression bundle.
 * All dependency inputs are explicit paths; hashes may be pinned via the
 * corresponding `*Sha256` options (enforced) or are computed and recorded.
 */
export async function buildCompression({
  billionContextDir,
  legacyAcpEntry,
  legacyAcpManifestPath,
  outDir,
  expectedVersion = BILLION_CONTEXT_VERSION,
  packageJsonSha256,
  serverEntrySha256,
  v2EntrySha256,
  legacyAcpSha256,
  legacyAcpUpstreamSourceSha256,
  generatedAt = new Date().toISOString(),
}) {
  if (!billionContextDir || !legacyAcpEntry || !outDir) {
    throw new Error("buildCompression requires billionContextDir, legacyAcpEntry and outDir");
  }
  const packageDir = resolve(billionContextDir);
  const pkg = JSON.parse(readFileSync(join(packageDir, "package.json"), "utf8"));
  if (pkg.name !== "billion-context" || pkg.version !== expectedVersion) {
    throw new Error(
      `billion-context mismatch: expected billion-context@${expectedVersion}, found ${pkg.name}@${pkg.version}`,
    );
  }
  const serverEntry = join(packageDir, "dist", "agent", "opencode-native.js");
  const v2Entry = join(packageDir, "dist", "agent", "opencode.js");
  const packageJsonPath = join(packageDir, "package.json");

  const computed = {
    packageJsonSha256: await sha256File(packageJsonPath),
    serverEntrySha256: await sha256File(serverEntry),
    v2EntrySha256: await sha256File(v2Entry),
    legacyAcpSha256: await sha256File(resolve(legacyAcpEntry)),
  };
  if (packageJsonSha256 && computed.packageJsonSha256 !== packageJsonSha256) {
    throw new Error(
      `package.json sha256 mismatch (expected ${packageJsonSha256}, found ${computed.packageJsonSha256})`,
    );
  }
  if (serverEntrySha256 && computed.serverEntrySha256 !== serverEntrySha256) {
    throw new Error(
      `v1 server entry sha256 mismatch (expected ${serverEntrySha256}, found ${computed.serverEntrySha256})`,
    );
  }
  if (v2EntrySha256 && computed.v2EntrySha256 !== v2EntrySha256) {
    throw new Error(
      `v2 entry sha256 mismatch (expected ${v2EntrySha256}, found ${computed.v2EntrySha256})`,
    );
  }
  if (legacyAcpSha256 && computed.legacyAcpSha256 !== legacyAcpSha256) {
    throw new Error(
      `legacy ACP entry sha256 mismatch (expected ${legacyAcpSha256}, found ${computed.legacyAcpSha256})`,
    );
  }
  const hashes = {
    packageJsonSha256: packageJsonSha256 ?? computed.packageJsonSha256,
    serverEntrySha256: serverEntrySha256 ?? computed.serverEntrySha256,
    v2EntrySha256: v2EntrySha256 ?? computed.v2EntrySha256,
    legacyAcpSha256: legacyAcpSha256 ?? computed.legacyAcpSha256,
  };

  const verification = await verifyBillionContextPackage({
    packageDir,
    expected: {
      version: expectedVersion,
      entries: {
        server: { path: serverEntry, sha256: hashes.serverEntrySha256, label: "server entry" },
        v2: { path: v2Entry, sha256: hashes.v2EntrySha256, label: "v2 bundle" },
      },
    },
  });
  if (!verification.ok) throw new Error(`dependency verification failed:\n  - ${verification.errors.join("\n  - ")}`);

  let legacyChanges = [];
  let legacyUpstreamVersion = undefined;
  if (legacyAcpManifestPath) {
    const manifest = JSON.parse(readFileSync(resolve(legacyAcpManifestPath), "utf8"));
    legacyUpstreamVersion = manifest.upstream?.["opencode-acp"];
    legacyChanges = manifest.changes ?? [];
  }

  const outAbs = resolve(outDir);
  const deps = {
    compression: {
      packageDir,
      version: expectedVersion,
      packageJsonSha256: hashes.packageJsonSha256,
      serverEntry: { path: serverEntry, sha256: hashes.serverEntrySha256 },
      v2Entry: { path: v2Entry, sha256: hashes.v2EntrySha256 },
      legacyAcp: {
        entry: { path: resolve(legacyAcpEntry), sha256: hashes.legacyAcpSha256 },
        slot: {
          // Install contract for the explicit BILI_OPENCODE_ACP_SPEC slot:
          // copy the emitted tree byte-exactly; the arm-time gate re-verifies
          // the installed slot against this sha256 (never stock bytes).
          emittedTree: "legacy-acp/opencode-acp",
          installedLayout:
            "<cacheHome>/opencode/packages/<SPEC>/node_modules/opencode-acp/dist/index.js",
          sha256: hashes.legacyAcpSha256,
          contract:
            "byte-exact copy of entry; arm-time gate verifies installed slot sha256 and refuses stock or foreign bytes",
        },
        upstreamSourceSha256: legacyAcpUpstreamSourceSha256 ?? null,
        upstreamVersion: legacyUpstreamVersion ?? null,
      },
    },
  };

  writeFile(outAbs, "deps.json", `${JSON.stringify(deps, null, 2)}\n`);
  // copy shared helpers + guarded entry modules from the source tree
  cpSync(join(srcRoot, "lib", "hash.mjs"), join(outAbs, "lib", "hash.mjs"));
  cpSync(join(srcRoot, "lib", "engine-registry.mjs"), join(outAbs, "lib", "engine-registry.mjs"));
  cpSync(join(srcRoot, "compression", "entry-core.mjs"), join(outAbs, "entry-core.mjs"));
  // engine-select keeps its source-tree relative layout (../lib/hash.mjs), so
  // it is emitted under compression/ exactly as it lives in src/.
  cpSync(join(srcRoot, "compression", "engine-select.mjs"), join(outAbs, "compression", "engine-select.mjs"));

  writeFile(outAbs, "v1.mjs", V1_ENTRY_TEMPLATE);
  writeFile(outAbs, "v2.mjs", V2_ENTRY_TEMPLATE);
  // Install contract: emit the repaired ACP entry as a DIRECT BYTE COPY so the
  // documented install steps yield a slot that satisfies the repaired-hash gate
  // by construction (no machine-local wrapper bytes, no baked absolute target).
  {
    const slotFile = join(outAbs, "legacy-acp", "opencode-acp", "dist", "index.js");
    mkdirSync(dirname(slotFile), { recursive: true });
    cpSync(resolve(legacyAcpEntry), slotFile);
    const emitted = await sha256File(slotFile);
    if (emitted !== hashes.legacyAcpSha256) {
      throw new Error(
        `internal: emitted legacy slot copy mismatch (expected ${hashes.legacyAcpSha256}, emitted ${emitted})`,
      );
    }
  }
  writeFile(
    outAbs,
    "package.json",
    `${JSON.stringify(
      {
        name: "opencode-community-compression",
        version: `0.0.0-bc${expectedVersion}`,
        private: true,
        type: "module",
        description: "Compression compatibility entries: billion-context for new sessions, repaired legacy ACP for old v1 sessions; at most one engine armed per bundle copy (per-copy registry, no process-global exclusion).",
        exports: {
          "./v1": "./v1.mjs",
          "./v2": "./v2.mjs",
        },
      },
      null,
      2,
    )}\n`,
  );

  const manifest = {
    generator: "opencode-community-compat/compression",
    generatedAt,
    upstream: {
      billionContext: {
        name: "billion-context",
        version: expectedVersion,
        resolution: packageDir,
        files: {
          packageJson: { path: packageJsonPath, sha256: hashes.packageJsonSha256 },
          serverEntry: { path: serverEntry, sha256: hashes.serverEntrySha256 },
          v2Bundle: { path: v2Entry, sha256: hashes.v2EntrySha256 },
        },
      },
      legacyAcp: {
        entry: { path: deps.compression.legacyAcp.entry.path, sha256: hashes.legacyAcpSha256 },
        upstreamVersion: legacyUpstreamVersion ?? null,
        upstreamSourceSha256: legacyAcpUpstreamSourceSha256 ?? null,
        changes: legacyChanges,
      },
    },
    selection: {
      legacyAcp: {
        envVar: "BILI_OPENCODE_ACP_SPEC",
        install:
          "copy legacy-acp/opencode-acp/ byte-exactly into <cacheHome>/opencode/packages/<SPEC>/node_modules/ and export BILI_OPENCODE_ACP_SPEC=<SPEC>; the emitted index.js is a byte-exact copy of the verified repaired entry, so the installed slot hash-equals the pin by construction",
        armGate:
          "the v1 wrapper arms ONLY when the explicit slot exists and its sha256 equals the pinned repaired hash; without the env var, with a missing slot, or on any content mismatch it refuses to arm — there is NO stock fallback, by design",
      },
      exactlyOneEngine:
        "per emitted bundle copy: at most one compression engine armed at a time; the second arm attempt (same or other kind) in that bundle copy throws. This is NOT process-global: separate bundle copies (e.g. different projects in one server process) keep separate registries and legitimately coexist. The v2 wrapper releases its claim when the host invokes the setup() cleanup; the v1 claim is held for the process lifetime of the armed bundle.",
    },
    tooling: {
      pinnedSurface:
        "billion-context 0.1.175 registers the tools compress, decompress, search_context, acp_status, acp_cache, absorb (an image_full name also exists in the bytes under imageCompression). acp_status IS present — old status surfaces are NOT removed.",
      transport:
        "registration alone is not a transport: the bili-backed tools (compress/decompress/search_context/acp_status/acp_cache/absorb) execute only against a live bili proxy. Per the pinned README (L150-199) the native v1/v2 plugins SELF-SPAWN the proxy — no extra launcher or env needed (self-managed port zone from 18787; a deliberate `bili start` daemon is attached by default). The launcher (`bili opencode`), BILLION_CONTEXT_PROXY and a /bili/-prefixed provider baseURL are the other documented postures and are what the tools' 'bili: no proxy detected' message suggests when no live proxy exists (e.g. a failed bootstrap). Packaging never rewrites user provider config, adds no mandatory launcher, and implements no alternative transport.",
      fixtureSafety:
        "pinned planNativeOpencode gating: BILLION_CONTEXT_PLUGIN=0 or BILI_NATIVE_OPENCODE=0 forces plan mode off (no spawn, no state writes). Tests that let the pinned fixture run for real must isolate HOME/XDG_CACHE_HOME/XDG_CONFIG_HOME, put the resolved real Node bin dir FIRST on PATH (mise shims break spawned bootstrap with a mismatched sandbox HOME: 'mise ERROR node is not a valid shim') and disable network side channels with ACP_AUTO_UPDATE=0 and BILI_ADVISORY_CHECK=0. Owner retest confirmed the native self-start route with a correct sandbox Node PATH and compaction.auto:false (search_context executed end-to-end).",
      hostInstall:
        "for real installs set \"compaction\": { \"auto\": false } in the host config (pinned README L150-199) or OpenCode's native auto-compaction double-compresses.",
      unsupportedSemantics:
        "no `recap` tool exists in the pinned 0.1.175 bundle (the word appears only in verbosity prompt text) — old recap-style summaries are reported as a GAP, not faked. Old absolute-token maxContextLimit values are translated only with a known model context limit and cannot be pinned across model sizes (see configSemantics).",
    },
    configSemantics:
      "old absolute-token thresholds are translated to explicit percent strings; minContextLimit/summaryBuffer/allowSubAgents/contextLimitFallback/minNudgeContextPercent/permission are dropped (see src/compression/config-semantics.mjs for reasons)",
    removal:
      "remove when no old v1 sessions remain and all hosts run compression natively; delete this bundle and the BILI_OPENCODE_ACP_SPEC slot",
  };
  writeFile(outAbs, "manifest.json", `${JSON.stringify(manifest, null, 2)}\n`);

  return {
    outDir: outAbs,
    files: [
      "package.json",
      "deps.json",
      "entry-core.mjs",
      "compression/engine-select.mjs",
      "lib/hash.mjs",
      "lib/engine-registry.mjs",
      "v1.mjs",
      "v2.mjs",
      "legacy-acp/opencode-acp/dist/index.js",
      "manifest.json",
    ],
    hashes,
  };
}
